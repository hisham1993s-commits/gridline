const LANG_KEY = 'f1live.lang';
const I18nContext = createContext({ lang: 'en', t: (k) => k, setLang: () => {} });

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState('en');

  useEffect(() => {
    AsyncStorage.getItem(LANG_KEY).then((v) => { if (v && STRINGS[v]) setLangState(v); });
  }, []);

  async function setLang(code) {
    setLangState(code);
    try { await AsyncStorage.setItem(LANG_KEY, code); } catch {}
  }

  const dict = STRINGS[lang] || STRINGS.en;
  const t = (key) => dict[key] ?? STRINGS.en[key] ?? key;

  return (
    <I18nContext.Provider value={{ lang, t, setLang }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
